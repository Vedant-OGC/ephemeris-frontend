// 24 Hour multi-satellite time series points for the main bottom chart
export const GENERATE_TIME_SERIES_DATA = (timeRangeHours: number = 24) => {
  const steps = 30;
  const data = [];
  const satKeys = ['NavIC-1A', 'NavIC-1B', 'NavIC-1C', 'NavIC-1D', 'NavIC-1E', 'NavIC-1F', 'NavIC-1G', 'NavIC-1I'];
  
  for (let i = 0; i <= steps; i++) {
    const ratio = i / steps;
    const hourOffset = Math.round(-timeRangeHours * (1 - ratio));
    const label = hourOffset === 0 ? 'Now' : `${hourOffset}h`;
    
    const t = i * 0.35;
    data.push({
      time: label,
      timeValue: hourOffset,
      'NavIC-1A': +(0.10 + Math.sin(t * 1.1 + 0.5) * 0.12).toFixed(2),
      'NavIC-1B': +(-0.05 + Math.sin(t * 0.9 + 2.1) * 0.18 + Math.cos(t * 1.5) * 0.08).toFixed(2),
      'NavIC-1C': +(0.04 + Math.cos(t * 1.3 + 1.2) * 0.14).toFixed(2),
      'NavIC-1D': +(0.22 + Math.sin(t * 0.8 + 3.4) * 0.20 + (ratio > 0.6 ? 0.1 : 0)).toFixed(2),
      'NavIC-1E': +(-0.02 + Math.cos(t * 1.2 + 0.8) * 0.15).toFixed(2),
      'NavIC-1F': +(0.08 + Math.sin(t * 1.4 + 4.2) * 0.18).toFixed(2),
      'NavIC-1G': +(0.06 + Math.sin(t * 0.7 + 1.8) * 0.16).toFixed(2),
      'NavIC-1I': +(-0.01 + Math.cos(t * 1.0 + 5.1) * 0.11).toFixed(2),
    });
  }
  return data;
};
